"""사용자가 고르는 진입점(MCP Prompts).

**양식은 새 기능이 아니라 자주 같이 쓰는 것들의 지름길이다.** 도구가 하는 일을 대신하지
않고, 몇 번 물어야 할 것을 한 번으로 줄인다. 도구(AI 가 고름)·instructions(무조건 실림)와
달리 **사용자가 골라야만 뜬다** — 안 고르면 아무 일도 안 일어난다.

무엇을 묶나: 사용자가 지금 손으로 3~4번 엮고 있는 조합. 도구 하나로 끝나는 것은 양식으로
감싸지 않는다 — 같은 것이 두 이름으로 존재해 AI 가 무엇을 고를지 흐려진다.

무엇을 적나: **이 묶음에서만 생기는 주의**만. 「없는 값을 지어내지 마라」 같은 전역 규칙은
server.py 의 instructions 가 모든 대화에 이미 싣는다 — 여기 또 적으면 이중장부가 된다.
"""

from __future__ import annotations


def register_all_prompts(mcp) -> None:

    @mcp.prompt(
        name="company_snapshot",
        title="회사 한 장 요약",
        description="재무·밸류에이션·지분구조·배당을 한 번에 훑어 한 장으로 정리합니다. "
                    "회사를 처음 볼 때의 첫 패스.",
    )
    def company_snapshot(company: str) -> str:
        """회사명 또는 종목코드 하나로 네 축을 묶어 본다."""
        return (
            f"{company} 를 한 장으로 정리해줘.\n"
            "\n"
            "순서:\n"
            "1. `company` 로 회사를 확정하고, 나온 이름·종목코드·corp_code 를 이어지는 호출에 그대로 넘긴다.\n"
            "2. `financial_metrics` — 매출·영업이익·순이익 추세, 차입과 이자보상배율\n"
            "3. `price_multiple_data` — PER·PBR·배당수익률, 그리고 그 값이 어느 기준으로 계산됐는지\n"
            "4. `ownership_structure` — 최대주주와 지분율, 주요 주주 구성\n"
            "5. `dividend` — 최근 배당 추이와 배당성향\n"
            "\n"
            "정리할 때:\n"
            "- 맨 위에 확정된 회사명과 종목코드를 쓴다.\n"
            "- 재무와 밸류에이션은 기준이 다를 수 있다(연결/별도, 회계연도, 지배주주 귀속 여부). "
            "다르면 맞추지 말고 다르다고 밝힌다.\n"
            "- 마지막에 「더 볼 것」을 세 줄 이내로 — 이 요약에서 걸리는 지점과 그것을 확인할 도구를 짚는다.\n"
        )

#!/usr/bin/env python3
"""krx_idx 스키마 — KRX 공식 지수(규모 대표·업종·섹터) 종가 표 둘과 접근 제어. **서버는 DDL 을 실행하지 않는다 — 사람이 배포 전에 한 번 적용한다.**

`scripts/krx_daily_ddl.py` 와 같은 모양(스크립트 안의 `CREATE … IF NOT EXISTS` 상수, 전부 멱등). 표만 만든다 — 행은 넣지 않는다.

    python3 scripts/krx_idx_ddl.py            # SQL 을 화면에 낸다. 아무것도 실행하지 않는다
    python3 scripts/krx_idx_ddl.py --no-tx    # BEGIN/COMMIT 없이 본문만
    python3 scripts/krx_idx_ddl.py --apply    # DATABASE_URL 의 DB 에 한 트랜잭션으로 적용한다
    python3 scripts/krx_idx_ddl.py --check    # 읽기 전용: 표·칸·기본키·RLS·권한이 이 스크립트의 모양인지 점검한다(쓰지 않는다)

■ 무엇을 담나 — KRX Open API `idx/kospi_dd_trd`·`idx/kosdaq_dd_trd`·`idx/krx_dd_trd` 의 일별 지수 종가(가격지수).
    응답에는 지수 코드 칸이 없다. 열쇠는 **(엔드포인트, 앞뒤 공백을 지운 이름)** 이다 — 20개 업종 이름이 코스피·코스닥 양쪽에 똑같이 있다.
    지수 구성 종목 원장 `krx_index_members` 와는 `idx_code`(kospi200·kosdaq150)로 잇기만 한다.

■ 표 `krx_idx_series` — 계열 사전(약 130행). 시세 표가 반복 text 열쇠 대신 정수 번호만 들고 가게 한다(`krx_ticker` 와 같은 원칙).
    sid       smallint 번호. 한 번 매기면 바뀌지 않는다. `GENERATED BY DEFAULT AS IDENTITY` — 적재가 정한 번호를 그대로 넣고(시퀀스는
              넣은 뒤 `setval` 로 맞춘다), 새 계열은 시퀀스가 매긴다.
    src       "char" 엔드포인트. P = kospi_dd_trd · Q = kosdaq_dd_trd · X = krx_dd_trd.
    name      text 앞뒤 공백을 지운 지수 이름(응답 IDX_NM). (src, name) 이 유일하다.
    kind      "char" z = 규모·시장 대표 · s = 업종·섹터 · t = 그 밖(테마·전략·소속부·총수익 등).
    in_db     boolean 이 계열의 종가 행이 **이 DB 에** 있는가. 거짓이면 이름·기간만 알려 주고 값은 opm-cold(`krx_idx_hist`)에 있다.
    first_dd, last_dd  date 수집한 범위에서 종가가 처음/마지막으로 있던 날(수집 시작 2015-12-30 앞의 역사는 모른다).
    idx_code  text `krx_index_members.index_code` 와 잇는 이름(kospi200 · kosdaq150). 나머지는 NULL. 값이 있으면 유일하다.
■ 표 `krx_idx` — 일별/주간 종가(한 행 = 계열 × 날짜). 기본키 (sid, trd_dd) 하나가 유일한 색인이다 — 날짜만으로 읽는 질의는 없다
    (한 계열의 구간 읽기와 한 날 단면은 모두 계열 수가 적어(≈130) 기본키로 끝난다).
    sid         smallint → krx_idx_series.sid
    trd_dd      date 거래일. 달력 표(`krx_day`)에 외래키를 걸지 않는다 — 창 앞 주간 점(주 닫는 날)은 달력에 없다.
    close_x100  integer 종가지수 × 100(응답은 소수 둘째 자리까지). 예: 5552.74 → 555274. 0 이하는 거절한다.
  보관 창이 날마다 한 날(83행)씩 밀려 지운 자리가 생긴다 — 죽은 행 2%(기본 20% 대신)에서 autovacuum 이 치우게 `krx_px` 와 같은 저장 옵션을 둔다.
  합성 2년 굴리기(83계열·520거래일, 로컬 PG17): 날마다 VACUUM 2.01 MiB · 2% 2.04 · 기본 20% 2.91 · 안 치우면 5.13 MiB.
  원응답의 나머지 칸(시고저·거래량·대금·시가총액·등락)은 DB 에 두지 않는다 — 콜드에 전 칸 그대로 둔다.
  행당 바이트: 힙 튜플 36 B(헤더 24 + 2 + 2 정렬 + 4 + 4) → 40 B 로 정렬 + 줄 포인터 4 + 기본키 색인 16 B 튜플 + 4 → 합성 적재로 잰 값은
  `tests/test_krx_idx_ddl.py::test_synthetic_load_row_bytes` 와 PR 본문에 있다.

■ 보관 모양(마스터 10-21 「3년 모양」): DB = **일별 창**(`krx_day` 보관 창과 같은 날들) + **주간 3년**(창 앞 ~ `krx_weekly_cutoff` 사이 「주 닫는 날」),
    그 앞은 opm-cold. 이 스크립트는 보관을 강제하지 않는다 — 정리는 쓰는 쪽(후속 갱신기 PR)이 같은 하한 함수로 한다.
■ 접근 제어 — 다른 표와 같은 꼴(RLS 켜기 + SELECT 정책 `USING (true)`). 서버 역할은 RLS 를 우회하고, 읽기 전용 역할(`opm_ro`)은
    이 정책 + 명시적 `GRANT SELECT` 로 읽는다. `anon`·`authenticated` 에는 권한을 주지 않는다(기본 권한 설정이 새 표에 자동으로
    주는 SELECT 를 명시적으로 거둔다 — 사전의 시퀀스도).
■ 서버 쓰기 권한은 이 스크립트가 주지 않는다. 서버 최소 권한 계정의 권한은 계정 스크립트가 따로 정한다.
"""
from __future__ import annotations

import argparse
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

#: 트랜잭션 본문 — BEGIN/COMMIT 은 `render()` 가 붙인다(`--apply` 는 psycopg 트랜잭션을 쓴다).
STATEMENTS = """\
CREATE TABLE IF NOT EXISTS krx_idx_series (
  sid      smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  src      "char"   NOT NULL CONSTRAINT krx_idx_series_src_ck CHECK (src IN ('P', 'Q', 'X')),   -- P=kospi_dd_trd Q=kosdaq_dd_trd X=krx_dd_trd
  name     text     NOT NULL CONSTRAINT krx_idx_series_name_ck CHECK (name <> '' AND name = btrim(name)),
  kind     "char"   NOT NULL CONSTRAINT krx_idx_series_kind_ck CHECK (kind IN ('z', 's', 't')), -- z 규모·시장 대표 / s 업종·섹터 / t 그 밖
  in_db    boolean  NOT NULL DEFAULT false,                                                     -- 거짓 = 값은 opm-cold krx_idx_hist 에만
  first_dd date,                                                                                -- 수집 범위에서 종가가 처음 있던 날
  last_dd  date,
  idx_code text,                                                                                -- krx_index_members.index_code (kospi200 · kosdaq150)
  CONSTRAINT krx_idx_series_src_name_key UNIQUE (src, name),
  CONSTRAINT krx_idx_series_dd_ck CHECK (first_dd IS NULL OR last_dd IS NULL OR first_dd <= last_dd)
);
CREATE UNIQUE INDEX IF NOT EXISTS krx_idx_series_idx_code_key ON krx_idx_series (idx_code) WHERE idx_code IS NOT NULL;

CREATE TABLE IF NOT EXISTS krx_idx (
  sid        smallint NOT NULL CONSTRAINT krx_idx_sid_fk REFERENCES krx_idx_series (sid),
  trd_dd     date     NOT NULL,
  close_x100 integer  NOT NULL CONSTRAINT krx_idx_close_ck CHECK (close_x100 > 0),   -- 종가지수 × 100 (5552.74 → 555274)
  CONSTRAINT krx_idx_pkey PRIMARY KEY (sid, trd_dd)
) WITH (autovacuum_vacuum_scale_factor = 0.02, autovacuum_analyze_scale_factor = 0.01);   -- 날마다 지우고 넣는 표 — 죽은 행 2% 에서 치운다

ALTER TABLE krx_idx_series ENABLE ROW LEVEL SECURITY;
ALTER TABLE krx_idx        ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS krx_idx_series_read ON krx_idx_series;
CREATE POLICY krx_idx_series_read ON krx_idx_series FOR SELECT USING (true);
DROP POLICY IF EXISTS krx_idx_read ON krx_idx;
CREATE POLICY krx_idx_read ON krx_idx FOR SELECT USING (true);

REVOKE ALL ON krx_idx_series, krx_idx FROM anon, authenticated;
REVOKE ALL ON SEQUENCE krx_idx_series_sid_seq FROM anon, authenticated;
GRANT SELECT ON krx_idx_series, krx_idx TO opm_ro;
"""

#: 점검용 — (표, 칸, 형, NOT NULL). 칸 순서도 이 순서여야 한다(행 모양이 곧 바이트다).
EXPECTED_COLUMNS = {
    "krx_idx_series": [("sid", "smallint", True), ("src", "char", True), ("name", "text", True), ("kind", "char", True),
                       ("in_db", "boolean", True), ("first_dd", "date", False), ("last_dd", "date", False), ("idx_code", "text", False)],
    "krx_idx": [("sid", "smallint", True), ("trd_dd", "date", True), ("close_x100", "integer", True)],
}
EXPECTED_PK = {"krx_idx_series": ["sid"], "krx_idx": ["sid", "trd_dd"]}
EXPECTED_RELOPTIONS = {"krx_idx": {"autovacuum_vacuum_scale_factor=0.02", "autovacuum_analyze_scale_factor=0.01"}}


def render() -> str:
    """사람이 SQL 편집기에 붙여 넣을 전체 스크립트."""
    return "BEGIN;\n\n" + STATEMENTS + "\nCOMMIT;\n"


def apply(url: str) -> None:
    import psycopg
    with psycopg.connect(url, connect_timeout=20) as con:      # 한 트랜잭션 — 중간에 실패하면 전부 되돌아간다
        con.execute("SET LOCAL lock_timeout = '3s'")
        con.execute(STATEMENTS)
        con.commit()


def check(url: str) -> list[str]:
    """읽기 전용 점검. 문제 목록을 돌려준다(빈 목록 = 이 스크립트의 모양 그대로)."""
    import psycopg
    problems: list[str] = []
    with psycopg.connect(url, connect_timeout=20) as con:
        con.execute("SET TRANSACTION READ ONLY")
        for table, cols in EXPECTED_COLUMNS.items():
            got = con.execute(
                "SELECT a.attname, format_type(a.atttypid, NULL), a.attnotnull FROM pg_attribute a "
                "WHERE a.attrelid = to_regclass(%s) AND a.attnum > 0 AND NOT a.attisdropped ORDER BY a.attnum", (f"public.{table}",)).fetchall()
            if not got:
                problems.append(f"{table}: 표가 없다")
                continue
            want = [(n, '"char"' if t == "char" else t, nn) for n, t, nn in cols]
            if [tuple(r) for r in got] != want:
                problems.append(f"{table}: 칸이 다르다 got={[tuple(r) for r in got]} want={want}")
            pk = [r[0] for r in con.execute(
                "SELECT a.attname FROM pg_index i JOIN pg_attribute a ON a.attrelid = i.indrelid AND a.attnum = ANY(i.indkey) "
                "WHERE i.indrelid = to_regclass(%s) AND i.indisprimary ORDER BY array_position(i.indkey::int2[], a.attnum)", (f"public.{table}",)).fetchall()]
            if pk != EXPECTED_PK[table]:
                problems.append(f"{table}: 기본키가 다르다 {pk}")
            want_opts = EXPECTED_RELOPTIONS.get(table, set())
            got_opts = {r[0] for r in con.execute("SELECT unnest(coalesce(reloptions, '{}')) FROM pg_class WHERE oid = to_regclass(%s)", (f"public.{table}",)).fetchall()}
            if want_opts - got_opts:
                problems.append(f"{table}: 저장 옵션이 없다 {sorted(want_opts - got_opts)}")
            if con.execute("SELECT relrowsecurity FROM pg_class WHERE oid = to_regclass(%s)", (f"public.{table}",)).fetchone()[0] is not True:
                problems.append(f"{table}: RLS 가 꺼져 있다")
            for role in ("anon", "authenticated"):
                for priv in ("SELECT", "INSERT", "UPDATE", "DELETE"):
                    if con.execute("SELECT has_table_privilege(%s, to_regclass(%s), %s)", (role, f"public.{table}", priv)).fetchone()[0]:
                        problems.append(f"{table}: {role} 에 {priv} 권한이 있다")
            if not con.execute("SELECT has_table_privilege('opm_ro', to_regclass(%s), 'SELECT')", (f"public.{table}",)).fetchone()[0]:
                problems.append(f"{table}: opm_ro 에 SELECT 권한이 없다")
    return problems


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--apply", action="store_true", help="DATABASE_URL 의 DB 에 적용 (없으면 SQL 만 출력)")
    ap.add_argument("--check", action="store_true", help="DATABASE_URL 의 DB 를 읽기 전용으로 점검")
    ap.add_argument("--no-tx", action="store_true", help="출력할 때 BEGIN/COMMIT 을 붙이지 않는다")
    args = ap.parse_args()
    if not (args.apply or args.check):
        sys.stdout.write(STATEMENTS if args.no_tx else render())
        return 0
    from dotenv import load_dotenv
    load_dotenv(ROOT / ".env")
    url = os.environ.get("DATABASE_URL")
    if not url:
        print("DATABASE_URL 이 없습니다 — 접속하지 않았습니다.", file=sys.stderr)
        return 2
    if args.check:
        problems = check(url)
        for p in problems:
            print("문제:", p)
        print("krx_idx 스키마 점검 통과." if not problems else f"문제 {len(problems)}건.")
        return 1 if problems else 0
    apply(url)
    print("krx_idx 스키마 적용 완료 (멱등 — 다시 실행해도 같은 결과).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

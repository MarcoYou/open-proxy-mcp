def test_v1_full_view_shape_and_privileges(pg17):
    _base(pg17, legacy=False)
    with psycopg.connect(pg17, autocommit=True) as c:
        c.execute(D.body("full"))
        c.execute(LEGACY_DDL.replace("wise_sector", "ref_shape").split(";")[0])
        cols = lambda rel: c.execute(  # noqa: E731
            "SELECT attname, atttypid::regtype::text, atttypmod FROM pg_attribute WHERE attrelid = %s::regclass "
            "AND attnum > 0 AND NOT attisdropped ORDER BY attnum", (rel,)).fetchall()
        assert cols("wise_sector") == cols("ref_shape")
        assert D.relkind(c) == "v"
        assert c.execute("SELECT count(*) FROM wise_sector").fetchone()[0] == 0
        # security_invoker: anon 은 뷰·밑 표 권한이 없다. opm_ro 는 뷰·밑 표·번호표를 모두 읽는다.
        c.execute("SET ROLE anon")
        with pytest.raises(psycopg.errors.InsufficientPrivilege):
            c.execute("SELECT * FROM wise_sector")
        c.execute("RESET ROLE")
        c.execute("SET ROLE opm_ro")
        assert c.execute("SELECT count(*) FROM wise_sector").fetchone()[0] == 0
        c.execute("RESET ROLE")
        # 두 번 돌려도 된다(멱등)
        c.execute(D.body("full"))


def test_v2_switch_equal_rows_folded_intervals(legacy):
    before = _rows(legacy)
    _switch(legacy)
    assert _kind(legacy) == "v" and _kind(legacy, "wise_sector_legacy") == "r"
    assert _rows(legacy) == before
    iv = _iv(legacy)
    # 005930 은 세 스냅샷 같은 값 → 한 구간(열린 끝). 000040 은 0821·0828 → 1016 에서 끝. 000070 은 C(0821·0828) → B(1016~).
    assert [r for r in iv if r[0] == "005930"] == [("005930", "2026-08-21", None, "W", "G4530", None)]
    assert [r for r in iv if r[0] == "000040"] == [("000040", "2026-08-21", "2026-10-16", "W", "G2510", None)]
    assert [r[1:4] + (r[4],) for r in iv if r[0] == "000070"] == [("2026-08-21", "2026-10-16", "W", "G3520"),
                                                                  ("2026-10-16", None, "W", "G4530")]

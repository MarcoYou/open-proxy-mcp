def _integrity(url):
    """구간 표 무결성(겹침·덜 접힘·빈 스냅샷·행 수) — 모두 0."""
    with psycopg.connect(url) as c:
        c.execute("CREATE TEMP TABLE _t (chk text, diff bigint)")
        c.execute(D.IV_CHECKS.format(t="_t"))
        return {k: v for k, v in c.execute("SELECT chk, diff FROM _t").fetchall()}



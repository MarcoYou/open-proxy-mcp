def test_v7_drop_legacy_only_when_legacy_rows_all_in_view(legacy, monkeypatch):
    _switch(legacy)
    monkeypatch.setenv("DATABASE_URL", legacy)
    monkeypatch.delenv("WICS_DATABASE_URL", raising=False)
    # 교체 뒤 0828 을 다시 수집해 000050 이 관측으로 바뀌었다 — 옛 표의 그 행(파생)은 이제 뷰에 없다 → 지우지 않는다
    assert S.rederive_db(dry_run=False) == 0
    with psycopg.connect(legacy, autocommit=True) as c:          # 옛 표를 교체 직전 다시 만들기 상태로 맞춰 둔다(운영과 같은 출발점)
        c.execute("DELETE FROM wise_sector_legacy")
        c.execute("INSERT INTO wise_sector_legacy SELECT * FROM wise_sector")
    assert S.persist(_snapshot("2026-08-28", {"000040": A, "000050": A, "005930": B, "000070": C}))
    with pytest.raises(psycopg.errors.RaiseException, match="뷰에 없다"):
        D.apply(legacy, "drop-legacy")
    assert _kind(legacy, "wise_sector_legacy") == "r"
    # 사람이 차이를 보고 옛 표를 지금 값으로 맞추면(또는 차이를 받아들이면) 지운다
    with psycopg.connect(legacy, autocommit=True) as c:
        c.execute("DELETE FROM wise_sector_legacy l WHERE NOT EXISTS (SELECT 1 FROM wise_sector v WHERE v.snap_dd = l.snap_dd "
                  "AND v.ticker = l.ticker AND v.src = l.src AND v.src_ref IS NOT DISTINCT FROM l.src_ref)")
    D.apply(legacy, "drop-legacy")
    assert _kind(legacy, "wise_sector_legacy") is None



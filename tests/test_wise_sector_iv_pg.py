def _steps(url, monkeypatch):
    """쓰는 쪽 시나리오 — 단계마다 행을 모은다."""
    monkeypatch.setenv("DATABASE_URL", url)
    monkeypatch.delenv("WICS_DATABASE_URL", raising=False)
    out = []
    _rederive(url)
    out.append(_rows(url))
    # 0828 을 다시 수집 — 000050 이 응답에 다시 있다(관측으로 돌아오고 그 뒤 스냅샷 이어 쓰기 출처도 바뀐다)
    assert S.persist(_snapshot("2026-08-28", {"000040": A, "000050": A, "005930": B, "000070": C}))
    out.append(_rows(url))
    # 1016 에 기업 화면 관측(번호표에 없는 950160 포함)
    company = [("000040", *A, "wise_company", "20261018:자동차"), ("950160", *C, "wise_company", "20261018:생물공학")]
    with psycopg.connect(url, autocommit=True) as c:
        c.execute("INSERT INTO krx_daily VALUES ('20261016', '950160')")
    assert S.persist(_snapshot("2026-10-16", {"005930": B, "000070": B}), company)
    out.append(_rows(url))
    # 새 스냅샷 1030(화면 못 봄 → 이어 쓰기)
    assert S.persist(_snapshot("2026-10-30", {"005930": B, "000070": B}))
    out.append(_rows(url))
    # 사이 날짜 0904 새 스냅샷(구간이 그 날에서 나뉘어야 한다 — 000070 이 그 날 A)
    assert S.persist(_snapshot("2026-09-04", {"000040": A, "005930": B, "000070": A}))
    out.append(_rows(url))
    # 1016 을 다시 수집 — 950160 이 구성종목으로 들어와 화면 관측을 이긴다
    assert S.persist(_snapshot("2026-10-16", {"005930": B, "000070": B, "950160": B}))
    out.append(_rows(url))
    return out


def _snapshot(day, rows):
    return {"requestedDate": day.replace("-", ""), "asOf": day, "sectorCount": 10, "industryCount": 28,
            "tickerCount": len(rows), "data": {t: {"sectorCode": cls[0], "sector": cls[1], "industryCode": cls[2],
                                                    "industry": cls[3]} for t, cls in rows.items()}}


def test_v4_writer_same_rows_in_table_and_view_mode(pg17, _pg17_server, monkeypatch):
    import uuid
    admin, url_for = _pg17_server
    other = "t_" + uuid.uuid4().hex[:10]
    with psycopg.connect(admin, autocommit=True) as c:
        c.execute(f'CREATE DATABASE "{other}"')
    try:
        url_v = url_for(other)
        _base(pg17)
        _base(url_v)
        _switch(url_v)
        table_steps = _steps(pg17, monkeypatch)
        view_steps = _steps(url_v, monkeypatch)
        for i, (t, v) in enumerate(zip(table_steps, view_steps)):
            assert t == v, f"단계 {i}"
        assert set(_integrity(url_v).values()) == {0}
        assert _kind(url_v) == "v"
        rows = {(r[0], r[1]): r[6:] for r in view_steps[-1]}
        assert rows[("20261016", "950160")] == ("wise", None)
        assert rows[("20261030", "950160")] == ("carry", "20261016")
        assert rows[("20260904", "000050")] == ("carry", "20260828")
        with psycopg.connect(url_v) as c:
            assert c.execute("SELECT count(*) FROM krx_ticker WHERE ticker = '950160'").fetchone()[0] == 1
            # 사이 날짜가 들어가 000070 이 C(0821·0828) → A(0904) → B(1016~) 세 구간
            assert c.execute("SELECT count(*) FROM wise_sector_iv i JOIN krx_ticker k USING (tid) "
                             "WHERE k.ticker = '000070'").fetchone()[0] == 3
            # 뷰 모드에서는 옛 모양 표를 만들지 않는다(옛 표 색인 이름이 비어도 뷰에 색인을 만들려 하지 않는다)
            assert D.relkind(c, "idx_wise_sector_ticker") is None
    finally:
        with psycopg.connect(admin, autocommit=True) as c:
            c.execute(f'DROP DATABASE IF EXISTS "{other}" WITH (FORCE)')


